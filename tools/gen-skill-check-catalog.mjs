#!/usr/bin/env node
/* sw25-ce: regenerate module/data/skill-check-catalog.mjs from generated class data.
 * Usage: node tools/gen-skill-check-catalog.mjs [path/to/gen/data/classes]
 * The output lists only check ids, their usual package group and ability: no class names, no rules text.
 * The sheet unions this list with the actor's own class items at runtime (homebrew checks add rows). */
import fs from "node:fs";
import path from "node:path";
import { buildCatalog, EXTRA_CHECKS } from "../module/rules/skill-checks.mjs";

const dir = process.argv[2] ?? path.resolve(import.meta.dirname, "../../gen/data/classes");
const defs = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
const cat = buildCatalog(defs.map((d) => d.classSkills ?? []), { extra: EXTRA_CHECKS });
const rows = cat.map((c) => `  { id: ${JSON.stringify(c.id)}, group: ${JSON.stringify(c.group)}, ability: ${JSON.stringify(c.ability)} },`);
const out = `/* sw25-ce: Skill Checks catalog (GENERATED by tools/gen-skill-check-catalog.mjs; do not edit by hand).
 * Check ids only: which package group they are listed under and the default ability. No class names.
 * At runtime the sheet adds any extra checks found on the actor's own class items (homebrew). */
export const SKILL_CHECK_CATALOG = [
${rows.join("\n")}
];
`;
const file = path.resolve(import.meta.dirname, "../module/data/skill-check-catalog.mjs");
fs.writeFileSync(file, out);
console.log(`wrote ${cat.length} checks -> ${path.relative(process.cwd(), file)}`);
